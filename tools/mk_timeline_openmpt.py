#!/usr/bin/env python3
"""mk_timeline_openmpt.py: cross-check re/s3mtime.model.json (own S3M walker, drove the Unicorn clock) against libopenmpt (set_position_order_row + get_position_seconds),
rewrite re/s3mtime.json with libopenmpt times and web/fx/timeline.js (pos(t), at(order,row)) so effects are locked to the audio the web player plays."""
import ctypes,json,os
H=os.path.dirname(os.path.abspath(__file__)); L=ctypes.CDLL('libopenmpt.so.0'); P=ctypes.c_void_p
d=open(H+'/../MUSTAKS.S3M','rb').read()
L.openmpt_module_create_from_memory2.restype=P; L.openmpt_module_create_from_memory2.argtypes=[ctypes.c_char_p,ctypes.c_size_t]+[P]*7
L.openmpt_module_get_position_seconds.restype=ctypes.c_double; L.openmpt_module_get_position_seconds.argtypes=[P]
L.openmpt_module_set_position_order_row.argtypes=[P,ctypes.c_int,ctypes.c_int]
L.openmpt_module_get_current_order.argtypes=[P]; L.openmpt_module_get_current_row.argtypes=[P]
m=L.openmpt_module_create_from_memory2(d,len(d),None,None,None,None,None,None,None)
j=json.load(open(H+'/../re/s3mtime.model.json')); out=[]; bad=0; md=0
for o,p,r,t in j['rows']:
    L.openmpt_module_set_position_order_row(m,o,r)
    if (L.openmpt_module_get_current_order(m),L.openmpt_module_get_current_row(m))!=(o,r): bad+=1
    s=L.openmpt_module_get_position_seconds(m); md=max(md,abs(s-t)); out.append([o,p,r,round(s,4)])
assert all(a[3]<=b[3] for a,b in zip(out,out[1:])),'not monotonic'
print(len(out),'rows; positions not reached exactly:',bad,'; max |model-openmpt| = %.3f s; last row model %.2f openmpt %.2f'%(md,j['rows'][-1][3],out[-1][3]))
json.dump({'rows':out,'orders':j['orders'],'duration':out[-1][3]},open(H+'/../re/s3mtime.openmpt.json','w'))
o=['// generated by tools/mk_timeline_openmpt.py - do not edit','export const ROWS=%s; // [order,pattern,row,start_s] libopenmpt'%json.dumps(out,separators=(',',':')),
'''export function pos(t){let lo=0,hi=ROWS.length-1;while(lo<hi){const m=(lo+hi+1)>>1;if(ROWS[m][3]<=t)lo=m;else hi=m-1}
const r=ROWS[lo];return{order:r[0],pattern:r[1],row:r[2],t0:r[3],i:lo}}
export function at(order,row){for(const r of ROWS)if(r[0]===order&&r[2]>=row)return r[3];return Infinity}''']
os.makedirs(H+'/../web/fx',exist_ok=True); open(H+'/../web/fx/timeline.js','w').write('\n'.join(o)+'\n')
